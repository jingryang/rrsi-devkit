def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Run AscendC-DevKit on cann-bench tasks: all selected tasks "
            "concurrently per trial, repeated --n times."
        )
    )
    parser.add_argument("--job", default="", help="RRSI job id (required unless --list)")
    parser.add_argument("--ids", default="", help="comma-separated operator ids")
    parser.add_argument(
        "--which", default="train", choices=["train", "heldout", "all"],
        help="task split when --ids is empty (default: train)",
    )
    parser.add_argument("--n", type=int, default=1, help="trials per task (default 1)")
    parser.add_argument("--limit", type=int, default=0, help="cap the number of tasks")
    parser.add_argument(
        "--runs-dir", default=str(cfg.RUNS_DIR),
        help="RRSI runs directory (default: bench.runs_dir from rrsi.json)",
    )
    parser.add_argument("--list", action="store_true", help="list configured tasks and exit")
    parser.add_argument(
        "--dry-run", action="store_true",
        help="write the trial-0 multi-task manifest and print the command",
    )
    parser.add_argument(
        "--force", action="store_true", help="rerun trials even when verdicts exist"
    )
    return parser.parse_args(argv)


def list_tasks() -> int:
    try:
        splits = tasklib.load_all()
    except tasklib.TaskError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    header = f"{'split':8} {'op':40} {'level':12} task"
    print(header)
    print("-" * len(header))
    for split, items in splits.items():
        for task in items:
            print(f"{split:8} {task.id:40} {task.level:12} {task.rel}")
    return 0


def dry_run(job: str, tasks, runs_dir: Path, cards: list[int]) -> int:
    python = cfg.python_bin()
    batch_dir = cfg.jobs_dir(runs_dir) / job / "dry-run"
    out_root = batch_dir / "devkit"
    items = [
        BatchItem(
            task=task,
            trial=0,
            attempts=1,
            run_id=f"t000-{task.id}",
            tdir=cfg.trial_dir(runs_dir, job, task.id, 0),
            worktree=batch_dir / "repos" / f"t000-{task.id}",
        )
        for task in tasks
    ]
    batch_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = batch_dir / "manifest.yaml"
    manifest_path.write_text(
        build_manifest(items, out_root, cards), encoding="utf-8"
    )
    print(f"manifest: {manifest_path}")
    print(manifest_path.read_text(encoding="utf-8"))
    print("command:")
    command = " ".join(
        shlex.quote(x) for x in build_command(manifest_path, out_root, python)
    )
    print("  " + command)
    return 0


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    if args.list:
        return list_tasks()
    if not args.job:
        print("error: --job is required", file=sys.stderr)
        return 2
    if args.n < 1:
        print("error: --n must be >= 1", file=sys.stderr)
        return 2

    try:
        selected = tasklib.select(args.ids, which=args.which, limit=args.limit)
    except tasklib.TaskError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if not selected:
        print("error: no tasks selected", file=sys.stderr)
        return 2

    problems = cfg.validate_environment()
    if problems:
        for problem in problems:
            print(f"[env] {problem}", file=sys.stderr)
        return 2
    if cfg.cann_env() is None:
        print("[env] warning: no CANN set_env.sh configured", file=sys.stderr)

    runs_dir = Path(args.runs_dir).expanduser().resolve()
    cards = cfg.detect_npu_ids() or [0]

    if args.dry_run:
        return dry_run(args.job, selected, runs_dir, cards)

    python = cfg.python_bin()
    started = time.time()
    results: list[dict] = []
    batch_tasks = 0
    batches = 0

    # 每一轮 trial 把训练集全部任务并发跑完，再进入下一轮。
    for trial in range(args.n):
        items, skipped = _plan_trial(selected, trial, runs_dir, args.job, args.force)
        for entry in skipped:
            results.append(entry)
            log(f"[trial] {entry['task_id']} t{entry['trial']}: skipped ({entry['reason']})")
        batch_tasks += len(items)
        if not items:
            continue

        batches += 1
        log(
            f"[run] trial={trial} tasks={len(items)} cards={cards} "
            f"python={python}"
        )
        results.extend(
            execute_batch(args.job, trial, items, runs_dir, cards, python)
        )

    for result in results:
        if result["status"] == "skipped":
            continue
        score = result.get("score")
        log(
            f"[trial] {result['task_id']} t{result['trial']}: {result['status']}"
            + (f" score={score:.4f}" if isinstance(score, (int, float)) else "")
        )

    counts: dict[str, int] = {}
    for result in results:
        status = result.get("status", "unknown")
        counts[status] = counts.get(status, 0) + 1

    summary = {
        "job": args.job,
        "tasks": [task.id for task in selected],
        "trials": len(selected) * args.n,
        "batches": batches,
        "batch_tasks": batch_tasks,
        "cards": cards,
        "counts": counts,
        "wall_s": round(time.time() - started, 3),
        "results": sorted(results, key=lambda r: (r["task_id"], r["trial"])),
    }
    summary_path = cfg.jobs_dir(runs_dir) / args.job / "summary.json"
    write_json(summary_path, summary)
    log(f"[run] summary: {summary_path}")
    log(json.dumps(counts, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
