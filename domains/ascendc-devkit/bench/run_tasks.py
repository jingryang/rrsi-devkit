"""在 cann-bench 任务上批量运行 AscendC-DevKit。

一次调用按 trial 轮次执行：每一轮把选中的全部任务放进同一个 DevKit
batch 并发运行，然后进入下一轮，共 ``--n`` 轮。每个任务在本轮内有独立
的 cann-bench worktree，任务失败互不影响。

用法：

    python3 run_tasks.py --job <job> --ids exp,softmax --n 1

路径与运行参数来自 ``domains/ascendc-devkit/rrsi.json`` 的 ``bench`` 段。
"""

