@dataclass
class BatchItem:
    task: object
    trial: int
    attempts: int
    run_id: str
    tdir: Path
    worktree: Path


def _pending_attempts(
    task, trial: int, runs_dir: Path, job: str, force: bool
) -> tuple[int | None, str]:
    """返回 (本次尝试序号, 跳过原因)；None 表示跳过。"""
    tdir = cfg.trial_dir(runs_dir, job, task.id, trial)
    if force:
        shutil.rmtree(tdir, ignore_errors=True)
        return 1, ""
    meta_path = tdir / "meta.json"
    verdict_path = tdir / "verdict.json"
    if meta_path.is_file() and verdict_path.is_file():
        return None, "done"
    previous = read_json(meta_path) or {}
    attempts = int(previous.get("attempts", 0)) + 1
    if meta_path.is_file() and attempts > MAX_ATTEMPTS:
        return None, "max_attempts"
    return attempts, ""


def _plan_trial(
    tasks, trial: int, runs_dir: Path, job: str, force: bool
) -> tuple[list[BatchItem], list[dict]]:
    items: list[BatchItem] = []
    skipped: list[dict] = []
    for task in tasks:
        attempts, reason = _pending_attempts(task, trial, runs_dir, job, force)
        if attempts is None:
            skipped.append(
                {
                    "task_id": task.id,
                    "trial": trial,
                    "dir": str(cfg.trial_dir(runs_dir, job, task.id, trial)),
                    "status": "skipped",
                    "reason": reason,
                }
            )
            continue
        run_id = f"t{trial:03d}-{task.id}"
        items.append(
            BatchItem(
                task=task,
                trial=trial,
                attempts=attempts,
                run_id=run_id,
                tdir=cfg.trial_dir(runs_dir, job, task.id, trial),
                worktree=Path(),
            )
        )
    return items, skipped


def _write_meta(
    item: BatchItem,
    base_meta: dict,
    status: str,
    retryable: bool,
    **fields,
) -> dict:
    meta = {
        **base_meta,
        "task_id": item.task.id,
        "op": item.task.id,
        "task_rel": item.task.rel,
        "trial": item.trial,
        "attempts": item.attempts,
        **fields,
        "status": status,
        "retryable": retryable,
    }
    write_json(item.tdir / "meta.json", meta)
    return {
        "task_id": item.task.id,
        "trial": item.trial,
        "dir": str(item.tdir),
        "status": status,
        "retryable": retryable,
        **({"score": fields["score"]} if "score" in fields else {}),
    }


def _match_snapshot(
    item: BatchItem, snapshots: list[Path], used: set[Path]
) -> Path | None:
    """优先按预分配的 run_id 匹配；否则按 ``op_name`` 唯一匹配。"""
    for snap in snapshots:
        if snap.parent.name == item.run_id and snap not in used:
            return snap
    candidates = [
        snap
        for snap in snapshots
        if snap not in used
        and (data := read_json(snap)) is not None
        and data.get("op_name") == item.task.id
    ]
    return candidates[0] if len(candidates) == 1 else None


def execute_batch(
    job: str,
    trial: int,
    items: list[BatchItem],
    runs_dir: Path,
    cards: list[int],
    python: Path,
) -> list[dict]:
    """用一个 DevKit batch 进程并发执行本轮 trial 的所有任务。"""
    stamp = (
        time.strftime("%Y%m%d-%H%M%S")
        + f"-t{trial:03d}-{os.getpid()}"
    )
    batch_dir = cfg.jobs_dir(runs_dir) / job / "batches" / stamp
    out_root = batch_dir / "devkit"
    manifest_path = batch_dir / "manifest.yaml"
    driver_log = batch_dir / "driver.log"
    batch_dir.mkdir(parents=True, exist_ok=True)

    started = time.time()
    base_meta = {
        "job": job,
        "manifest": str(manifest_path),
        "output_root": str(out_root),
        "driver_log": str(driver_log),
        "batch_dir": str(batch_dir),
        "cards": cards,
        "env": {
            "chip": cfg.CHIP,
            "cann_env": str(cfg.cann_env() or ""),
            "cann_bench": str(cfg.CANN_BENCH),
            "harness": str(cfg.HARNESS),
            "python": str(python),
            **cfg.harness_ref(),
        },
    }

    # 每个任务独立 worktree；创建失败的任务直接记为 infra_error。
    active: list[BatchItem] = []
    results: list[dict] = []
    for item in items:
        item.worktree = batch_dir / "repos" / item.run_id
        try:
            _add_worktree(item.worktree)
        except Exception as exc:  # noqa: BLE001
            results.append(
                _write_meta(
                    item,
                    base_meta,
                    "infra_error",
                    True,
                    error=f"{type(exc).__name__}: {exc}",
                    traceback=traceback.format_exc(limit=20),
                )
            )
            continue
        shutil.rmtree(item.tdir / "op_src", ignore_errors=True)
        (item.tdir / "verdict.json").unlink(missing_ok=True)
        active.append(item)

    if not active:
        return results

    try:
        # 轮内所有任务同时提交；卡数不足时由 DevKit 卡池在 NPU 阶段排队。
        manifest_path.write_text(
            build_manifest(active, out_root, cards), encoding="utf-8"
        )
        out_root.mkdir(parents=True, exist_ok=True)

        cmd = build_command(manifest_path, out_root, python)
        env = build_env(python)
        # 所有任务并行启动，各自受 workflow_timeout_sec 约束。
        hard_timeout = (
            cfg.TRIAL_TIMEOUT + cfg.HARD_TIMEOUT_GRACE
            if cfg.TRIAL_TIMEOUT > 0
            else 0
        )

        timed_out = False
        with open(driver_log, "wb") as logf:
            proc = subprocess.Popen(
                cmd,
                cwd=str(cfg.HARNESS),
                env=env,
                stdout=logf,
                stderr=subprocess.STDOUT,
                start_new_session=True,
            )
            try:
                returncode = proc.wait(timeout=hard_timeout or None)
            except subprocess.TimeoutExpired:
                timed_out = True
                _kill_group(proc)
                returncode = proc.returncode

        log_text = driver_log.read_text(encoding="utf-8", errors="replace")
        match = BATCH_ID_RE.search(log_text)
        batch_id = match.group(1) if match else ""
        snapshots = find_snapshots(out_root, batch_id)
        used: set[Path] = set()
        wall = time.time() - started
        common = {
            "batch_id": batch_id,
            "command": " ".join(shlex.quote(x) for x in cmd),
            "exit_code": returncode,
            "timed_out": timed_out,
            "log_tail": "\n".join(log_text.splitlines()[-40:]),
        }

        for item in active:
            snap = _match_snapshot(item, snapshots, used)
            if snap is None:
                results.append(
                    _write_meta(
                        item,
                        base_meta,
                        "timeout" if timed_out else "harness_error",
                        True,
                        **common,
                        snapshot="",
                    )
                )
                continue

            used.add(snap)
            snapshot_data = read_json(snap)
            if snapshot_data is None:
                verdict = verdict_from_snapshot({}, wall, snap)
                verdict["status"] = "harness_error"
                verdict["checks"] = ["state_snapshot.json is not valid JSON"]
            else:
                verdict = verdict_from_snapshot(snapshot_data, wall, snap)
            write_json(item.tdir / "verdict.json", verdict)

            copied = copy_op_sources(item.worktree, item.task.id, item.tdir / "op_src")
            card = snapshot_data.get("npu_id") if isinstance(snapshot_data, dict) else None
            status = verdict["status"] if verdict["valid"] >= 1.0 else "harness_error"
            score = verdict["score"] if verdict["valid"] >= 1.0 else 0.0
            results.append(
                _write_meta(
                    item,
                    base_meta,
                    status,
                    False,
                    **common,
                    snapshot=str(snap),
                    exec_id=snap.parent.name,
                    card=card,
                    op_src_files=copied,
                    score=score,
                )
            )
    except Exception as exc:  # noqa: BLE001
        error = f"{type(exc).__name__}: {exc}"
        tb = traceback.format_exc(limit=20)
        done = {f"{r['task_id']}:{r['trial']}" for r in results}
        for item in active:
            if f"{item.task.id}:{item.trial}" in done:
                continue
            results.append(
                _write_meta(
                    item, base_meta, "infra_error", True, error=error, traceback=tb
                )
            )
    finally:
        if not cfg.KEEP_WORKTREES:
            for item in active:
                try:
                    _remove_worktree(item.worktree)
                except Exception as exc:  # noqa: BLE001
                    log(f"[warn] failed to remove worktree {item.worktree}: {exc}")

    return results


