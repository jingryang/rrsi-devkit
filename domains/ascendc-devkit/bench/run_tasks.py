def log(msg: str) -> None:
    print(msg, flush=True)


def read_json(path: Path) -> dict | None:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001
        return None


def write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    tmp.replace(path)


def _fnum(mapping: dict, key: str, default: float = 0.0) -> float:
    try:
        value = mapping.get(key)
        return float(value) if value is not None else default
    except (TypeError, ValueError):
        return default


def _inum(mapping: dict, key: str, default: int = 0) -> int:
    try:
        value = mapping.get(key)
        return int(value) if value is not None else default
    except (TypeError, ValueError):
        return default


def _as_mapping(value) -> dict | None:
    if isinstance(value, str):
        try:
            value = json.loads(value)
        except Exception:  # noqa: BLE001
            return None
    return value if isinstance(value, dict) else None


def _yaml_scalar(value: str) -> str:
    """YAML 标量；不含 ``:``，避免被解析成映射。"""
    text = str(value)
    if re.fullmatch(r"[A-Za-z0-9_./+=-]+", text):
        return text
    return "'" + text.replace("'", "''") + "'"


def _kill_group(proc: subprocess.Popen) -> None:
    """终止整个进程组（包括 opencode 子进程）。"""
    for sig, grace in ((signal.SIGTERM, 30), (signal.SIGKILL, 10)):
        try:
            os.killpg(os.getpgid(proc.pid), sig)
        except ProcessLookupError:
            return
        try:
            proc.wait(timeout=grace)
            return
        except subprocess.TimeoutExpired:
            continue


