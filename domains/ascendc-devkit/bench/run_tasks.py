def _optional_file(primary: Path, fallback: Path, name: str) -> Path | None:
    for base in (primary, fallback):
        candidate = base / name
        if candidate.is_file():
            return candidate
    return None


def build_manifest(items: list["BatchItem"], out_root: Path, cards: list[int]) -> str:
    """为一轮 trial 生成 manifest；轮内所有任务并发执行。"""
    lines = [
        "# generated by domains/ascendc-devkit/bench/run_tasks.py",
        f"output_root: {_yaml_scalar(out_root)}",
        f"cards: [{', '.join(str(c) for c in cards)}]",
        f"design_concurrency: {len(items)}",
        f"repo_profile: {_yaml_scalar(cfg.REPO_PROFILE)}",
        "non_interactive: true",
        "on_decision: default",
        "workflow: self_evolve_op",
        "mode: new",
        f"workflow_timeout_sec: {cfg.TRIAL_TIMEOUT}",
        f"stage_timeout_sec: {cfg.STAGE_TIMEOUT}",
        "tasks:",
    ]

    for item in items:
        task = item.task
        task_dir = item.worktree / task.rel
        lines.extend(
            [
                f"  - op_dir: {_yaml_scalar(item.worktree / cfg.OP_SUBDIR / task.id)}",
                f"    repo_root: {_yaml_scalar(item.worktree)}",
                f"    run_id: {_yaml_scalar(item.run_id)}",
                f"    requirement_path: {_yaml_scalar(task_dir / 'proto.yaml')}",
                f"    golden_path: {_yaml_scalar(task_dir / 'golden.py')}",
                f"    golden_entry: {_yaml_scalar(task.id)}",
                "    golden_input_type: torch",
            ]
        )
        cases_csv = _optional_file(task_dir, task.path, "cases.csv")
        if cases_csv is not None:
            lines.append(f"    cases_path: {_yaml_scalar(cases_csv)}")
        aux = [
            path
            for name in ("desc.md", "design.md")
            if (path := _optional_file(task_dir, task.path, name)) is not None
        ]
        if aux:
            lines.append("    requirement_aux_paths:")
            lines.extend(f"      - {_yaml_scalar(path)}" for path in aux)
        if cfg.CHIP:
            lines.append(f"    design_target_chip: {_yaml_scalar(cfg.CHIP)}")

    return "\n".join(lines) + "\n"


def build_command(manifest: Path, out_root: Path, python: Path) -> list[str]:
    args = [
        str(python),
        "-c",
        ENTRY,
        "run",
        "--batch",
        str(manifest),
        "--output-root",
        str(out_root),
        "--non-interactive",
    ]
    inner = " ".join(shlex.quote(arg) for arg in args)

    lines = ["set +u"]
    env_script = cfg.cann_env()
    if env_script is not None:
        lines.append(f"source {shlex.quote(str(env_script))}")
    lines.append("set -u")
    lines.append(f"exec {inner}")
    return ["bash", "-c", "; ".join(lines)]


def build_env(python: Path) -> dict[str, str]:
    """候选源码优先；PATH 前置 3.12 供 scorer 内部的 ``python`` 使用。"""
    env = os.environ.copy()
    src = str(cfg.HARNESS / "src")
    previous = env.get("PYTHONPATH", "")
    env["PYTHONPATH"] = src + (os.pathsep + previous if previous else "")
    env["PATH"] = str(python.parent) + os.pathsep + env.get("PATH", "")
    env["PYTHONUNBUFFERED"] = "1"
    return env


